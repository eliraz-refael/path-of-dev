import { describe, expect, test } from 'claude-code/testing'
import type { ImportedHistory } from '@pathofdev/schema'
import {
  countsOf,
  freshTally,
  historyAskOf,
  historyRows,
  historyUsage,
  importedText,
  isHistoryAnswer,
  isPrompt,
  isTranscript,
  lineReader,
  longestStreakOf,
  nothingBeforeText,
  projectsDirOf,
  restoreTally,
  savedTally,
  tallyLine,
  tallyText,
  toolKindOf,
} from './history'

// What a Claude Code transcript counts as, from lines built by hand in the shape its JSONL takes: a typed prompt, an
// answer's tool calls, and everything else (tool results, commands' output, meta lines, summaries, junk) as nothing;
// what is dated from the player's start on as nothing too; and the counts the mod sends.

const before = Date.parse('2026-10-09T08:00:00Z')
const tally = () => freshTally(before, 'UTC')

/** A user line as Claude Code writes one. */
const user = (content: unknown, at = '2026-10-01T10:00:00.000Z', more: Record<string, unknown> = {}) =>
  JSON.stringify({ type: 'user', uuid: `u-${Math.random()}`, timestamp: at, sessionId: 's1', cwd: '/work/acme-secret', message: { role: 'user', content }, ...more })

/** An assistant line with `blocks` for its content. */
const assistant = (blocks: ReadonlyArray<unknown>, at = '2026-10-01T10:00:05.000Z') =>
  JSON.stringify({ type: 'assistant', uuid: `a-${Math.random()}`, timestamp: at, message: { role: 'assistant', content: blocks } })

const tool = (id: string, name: string, input: unknown = {}) => ({ type: 'tool_use', id, name, input })

describe('a transcript line', () => {
  test('counts a prompt the player typed, as text or as text blocks, and an image alone', () => {
    const counted = tally()
    tallyLine(counted, user('fix the flaky login test'), '-work-acme', 's1')
    tallyLine(counted, user([{ type: 'text', text: 'and this one' }]), '-work-acme', 's1')
    tallyLine(counted, user([{ type: 'image', source: { type: 'base64', data: 'AAAA' } }]), '-work-acme', 's1')
    expect(countsOf(counted).prompts).toBe(3)
  })

  test("counts no tool result, command, command output, shell command, meta line or anything Claude Code wrote", () => {
    const counted = tally()
    const lines = [
      user([{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }]),
      user([{ type: 'text', text: 'note' }, { type: 'tool_result', tool_use_id: 't2', content: 'ok' }]),
      user('<command-name>/review</command-name>\n<command-message>review</command-message>'),
      user('<local-command-stdout>done</local-command-stdout>'),
      user('<bash-input>ls</bash-input>'),
      user('<task-notification>finished</task-notification>'),
      user('[Request interrupted by user]'),
      user('Caveat: The messages below were generated by the user while running local commands.'),
      user('a summary of the conversation so far', undefined, { isCompactSummary: true }),
      user('expanded skill text', undefined, { isMeta: true }),
      user('ok', undefined, { toolUseResult: { stdout: 'ok' } }),
      user('a subagent prompt', undefined, { isSidechain: true }),
      user('   '),
      user(42),
      JSON.stringify({ type: 'summary', summary: 'Fixing the login test', leafUuid: 'x' }),
      JSON.stringify({ type: 'file-history-snapshot', snapshot: {} }),
      JSON.stringify({ type: 'system', content: 'compacted', timestamp: '2026-10-01T10:00:00.000Z' }),
    ]
    for (const line of lines) tallyLine(counted, line, '-work-acme', 's1')
    expect(countsOf(counted)).toMatchObject({ prompts: 0, sessions: 0, projects: 0, days: 0 })
  })

  test('counts nothing from a line that does not parse, or has no usable timestamp, and never throws', () => {
    const counted = tally()
    const lines = [
      '{"type":"user","message":{"content":"half a line',
      'not json at all "user"',
      '"user"',
      'null',
      '[]',
      user('no time', 'yesterday'),
      JSON.stringify({ type: 'user', message: { content: 'no timestamp at all' } }),
      JSON.stringify({ type: 'user', timestamp: 3, message: { content: 'a number for a time' } }),
      JSON.stringify({ type: 'user', timestamp: '2026-10-01T10:00:00Z', message: 'not an object' }),
      JSON.stringify({ type: 'assistant', timestamp: '2026-10-01T10:00:00Z', message: { content: 'text, not blocks' } }),
      assistant([null, 3, { type: 'tool_use' }, { type: 'tool_use', id: 7, name: 'Bash' }, { type: 'tool_use', id: 'x' }]),
    ]
    for (const line of lines) expect(() => tallyLine(counted, line, 'p', 's')).not.toThrow()
    expect(countsOf(counted)).toMatchObject({ prompts: 0, tools: { bash: 0, other: 0 } })
  })

  test('counts nothing dated at or after the player started, and everything before', () => {
    const counted = tally()
    tallyLine(counted, user('just before', '2026-10-09T07:59:59.999Z'), 'p', 's')
    tallyLine(counted, user('right at the start', '2026-10-09T08:00:00.000Z'), 'p', 's')
    tallyLine(counted, user('after', '2026-10-10T09:00:00.000Z'), 'p', 's')
    tallyLine(counted, user('an offset, before', '2026-10-09T09:59:00+02:00'), 'p', 's')
    tallyLine(counted, assistant([tool('t1', 'Bash', { command: 'pnpm test' })], '2026-10-09T08:00:01Z'), 'p', 's')
    expect(countsOf(counted)).toMatchObject({ prompts: 2, testRuns: 0, tools: { bash: 0 } })
  })

  test("counts each tool call once by its id, under its kind, and a Bash call's test runs and commits", () => {
    const counted = tally()
    const bash = tool('t1', 'Bash', { command: 'pnpm test && git add -A && git commit -m "pnpm test fix for acme-secret"' })
    tallyLine(counted, assistant([{ type: 'text', text: 'running' }, bash]), 'p', 's')
    // The same message again, as a resumed session copies it, or split over two lines as answers are.
    tallyLine(counted, assistant([bash]), 'p', 's')
    tallyLine(counted, assistant([tool('t2', 'Read'), tool('t3', 'Edit'), tool('t4', 'Write'), tool('t5', 'Grep')]), 'p', 's')
    tallyLine(counted, assistant([tool('t6', 'mcp__acme-secret__deploy'), tool('t7', 'Agent'), tool('t8', 'WebFetch')]), 'p', 's')
    tallyLine(counted, assistant([tool('t9', 'TodoWrite'), tool('t10', 'Bash', { command: 'echo "pnpm test"' })]), 'p', 's')
    expect(countsOf(counted)).toMatchObject({
      tools: { bash: 2, read: 1, edit: 2, search: 1, web: 1, agent: 1, mcp: 1, other: 1 },
      testRuns: 1,
      commits: 1,
    })
  })

  test('counts a prompt once by its id, as a resumed session copies the messages before it', () => {
    const counted = tally()
    const line = JSON.stringify({ type: 'user', uuid: 'same', timestamp: '2026-10-01T10:00:00Z', message: { content: 'hello' } })
    tallyLine(counted, line, 'p', 'first')
    tallyLine(counted, line, 'p', 'resumed')
    expect(countsOf(counted)).toMatchObject({ prompts: 1, sessions: 1 })
  })
})

describe('the counts', () => {
  test('count sessions, projects and local days with a prompt, the first and last day, and the longest run of days', () => {
    const counted = freshTally(before, 'America/Los_Angeles')
    const text = [
      // 2026-09-01 03:00Z is still Aug 31 in Los Angeles.
      user('one', '2026-09-01T03:00:00Z'),
      user('two', '2026-09-01T18:00:00Z'),
      user('three', '2026-09-02T18:00:00Z'),
      user('four', '2026-09-03T18:00:00Z'),
      '',
      'junk',
    ].join('\n')
    tallyText(counted, text, '-work-a', 's1')
    tallyLine(counted, user('five', '2026-09-20T18:00:00Z'), '-work-b', 's2')
    tallyLine(counted, user('six', '2026-09-20T19:00:00Z'), '-work-b', 's3')
    // A session with only tool calls counts as no session.
    tallyLine(counted, assistant([tool('t1', 'Read')], '2026-09-21T18:00:00Z'), '-work-c', 's4')
    expect(countsOf(counted)).toEqual({
      prompts: 6,
      sessions: 3,
      projects: 2,
      days: 5,
      longestStreak: 4,
      tools: { bash: 0, read: 1, edit: 0, search: 0, web: 0, agent: 0, mcp: 0, other: 0 },
      testRuns: 0,
      commits: 0,
      firstDay: '2026-08-31',
      lastDay: '2026-09-20',
    })
  })

  test('go back to what they were before a file that failed part way, leaving nothing of it counted', () => {
    const counted = tally()
    tallyText(counted, [user('one', '2026-09-01T10:00:00Z'), assistant([tool('t1', 'Bash', { command: 'pnpm test' })])].join('\n'), '-a', 's1')
    const first = countsOf(counted)
    const saved = savedTally(counted)
    tallyText(counted, [user('two', '2026-09-02T10:00:00Z'), assistant([tool('t2', 'Bash', { command: 'git commit -m x' })])].join('\n'), '-b', 's2')
    expect(countsOf(counted)).not.toEqual(first)
    restoreTally(counted, saved)
    expect(countsOf(counted)).toEqual(first)
    // And counting goes on from there as if the file had never been read.
    tallyLine(counted, user('three', '2026-09-02T10:00:00Z'), '-b', 's2')
    expect(countsOf(counted)).toMatchObject({ prompts: 2, sessions: 2, projects: 2, days: 2, commits: 0 })
  })

  test('are all zero, and no day, from nothing', () => {
    expect(countsOf(tally())).toMatchObject({ prompts: 0, days: 0, longestStreak: 0, firstDay: null, lastDay: null })
  })

  test('take the longest run of days in a row, across a month and a year', () => {
    expect(longestStreakOf([])).toBe(0)
    expect(longestStreakOf(['2026-01-05'])).toBe(1)
    expect(longestStreakOf(['2025-12-30', '2025-12-31', '2026-01-01', '2026-01-03'])).toBe(3)
    expect(longestStreakOf(['2026-03-01', '2026-02-28', '2026-02-27', '2026-02-27'])).toBe(3)
    expect(longestStreakOf(['2024-02-28', '2024-03-01'])).toBe(1)
  })
})

describe('the files', () => {
  test('are each session’s transcript, under the config folder or ~/.claude', () => {
    expect(projectsDirOf(undefined, '/home/player')).toBe('/home/player/.claude/projects')
    expect(projectsDirOf('', '/home/player')).toBe('/home/player/.claude/projects')
    expect(projectsDirOf('/srv/claude/', '/home/player')).toBe('/srv/claude/projects')
    expect(projectsDirOf(undefined, undefined)).toBeNull()
    const file = (name: string, kind = 'file') => isTranscript({ name, kind })
    expect(file('2b8c7c1e-1111-4a5b-9c3d-000000000000.jsonl')).toBe(true)
    expect(file('2b8c7c1e.orphaned-1760000000-ab.jsonl')).toBe(false)
    expect(file('2b8c7c1e.jsonl.superseded-1760000000')).toBe(false)
    expect(file('agent-1234.jsonl')).toBe(false)
    expect(file('memory', 'dir')).toBe(false)
    expect(file('notes.md')).toBe(false)
  })

  test('are read line by line however the stream cuts them, and a line past the limit is dropped whole', () => {
    const lines: Array<string> = []
    const reader = lineReader((line) => lines.push(line), 10)
    for (const piece of ['ab', 'c\nde', 'f\n\ng', 'hij', 'klmnop', 'qrs\nshort\nt', 'ail']) reader.push(piece)
    reader.end()
    expect(lines).toEqual(['abc', 'def', '', 'short', 'tail'])
  })

  test('name each tool by its kind alone', () => {
    expect(toolKindOf('mcp__acme__deploy')).toBe('mcp')
    expect(toolKindOf('Task')).toBe('agent')
    expect(toolKindOf('NotebookEdit')).toBe('edit')
    expect(toolKindOf('SomethingNew')).toBe('other')
  })
})

describe('the command and its reply', () => {
  test('is /pathofdev import history, and anything else under import is the usage', () => {
    expect(historyAskOf('import history')).toEqual({ kind: 'import' })
    expect(historyAskOf('  import   history ')).toEqual({ kind: 'import' })
    expect(historyAskOf('import')).toBe(historyUsage)
    expect(historyAskOf('import history now')).toBe(historyUsage)
    expect(historyAskOf('profile')).toBeNull()
  })

  const counts = {
    prompts: 1234,
    sessions: 210,
    projects: 14,
    days: 96,
    longestStreak: 12,
    tools: { bash: 3000, read: 4000, edit: 1500, search: 300, web: 50, agent: 40, mcp: 10, other: 1 },
    testRuns: 412,
    commits: 230,
    firstDay: '2025-03-02',
    lastDay: '2026-10-08',
  }

  test('sums the numbers up and says how to show them, online on the profile and locally in the pane', () => {
    expect(importedText(counts, { kind: 'online', origin: 'https://api.pathof.dev' }, 0)).toBe(
      'Imported your Claude Code history from before Path of Dev (2025-03-02 to 2026-10-08): 1,234 prompts in 210 ' +
        'sessions across 14 projects, on 96 days (longest streak 12 days); 8,901 tool calls, 412 test runs and 230 ' +
        'commits. Only these counts left this machine: no prompt, code, path or project name. It earns no XP. It shows ' +
        'in the Stats tab of /pathofdev, and starts hidden on your public page: /pathofdev profile show history adds it.',
    )
    expect(importedText({ ...counts, prompts: 1, sessions: 1, projects: 1, days: 1, longestStreak: 1, lastDay: '2025-03-02' }, { kind: 'local' }, 2)).toBe(
      'Imported your Claude Code history from before Path of Dev (2025-03-02): 1 prompt in 1 session across 1 project, ' +
        'on 1 day (longest streak 1 day); 8,901 tool calls, 412 test runs and 230 commits. Only these counts left this ' +
        'machine: no prompt, code, path or project name. It earns no XP. It shows in the Stats tab of /pathofdev. 2 ' +
        'transcripts could not be read and were left out.',
    )
    expect(nothingBeforeText('2026-10-09T08:00:00.000Z', 3, 1)).toBe(
      'None of your 3 Claude Code transcripts has a prompt from before you started Path of Dev on 2026-10-09, and 1 ' +
        'transcript could not be read: nothing to import.',
    )
  })

  test('takes a server answer with the counts it draws, and none without', () => {
    const history: ImportedHistory = { ...counts, importedAt: '2026-10-09T08:00:00.000Z' }
    expect(isHistoryAnswer({ history, before: '2026-10-09T08:00:00.000Z' })).toBe(true)
    expect(isHistoryAnswer({ history: null, before: '2026-10-09T08:00:00.000Z' })).toBe(true)
    expect(isHistoryAnswer({ history: { ...history, prompts: '1' }, before: 'x' })).toBe(false)
    expect(isHistoryAnswer({ history })).toBe(false)
    // A start that is no time would let every line count.
    expect(isHistoryAnswer({ history: null, before: 'soon' })).toBe(false)
    expect(isHistoryAnswer(null)).toBe(false)
  })

  test("lists in the Stats tab each kind of tool call there were, and leaves out the rest", () => {
    const history: ImportedHistory = { ...counts, tools: { ...counts.tools, web: 0, agent: 0 }, importedAt: '2026-10-09T08:00:00.000Z' }
    const rows = historyRows(history).map((row) => `${row.label.map((run) => run.text).join('')}=${row.value}`)
    expect(rows).toEqual([
      'Prompts=1,234',
      'Sessions=210',
      'Days active=96',
      'Longest streak=12 days',
      'Projects=14',
      'Tool calls=8,811',
      '├ Bash=3,000',
      '├ reads=4,000',
      '├ edits=1,500',
      '├ searches=300',
      '├ MCP=10',
      '└ other=1',
      'Test runs=412',
      'Commits=230',
    ])
  })
})

describe('isPrompt', () => {
  test('reads a user line by its content and flags alone', () => {
    expect(isPrompt({ message: { content: 'hi' } })).toBe(true)
    expect(isPrompt({ message: { content: 'hi' }, isSynthetic: true })).toBe(false)
    expect(isPrompt({ message: { content: 'hi' }, isVisibleInTranscriptOnly: true })).toBe(false)
    expect(isPrompt({ message: {} })).toBe(false)
    expect(isPrompt({})).toBe(false)
  })
})
